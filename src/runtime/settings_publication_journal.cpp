constexpr std::size_t kDxvkLimit = 256 * 1024;
constexpr const char* kDxvkHeader = "# Generated by Playden from this game's settings.";
struct Writer {
  static constexpr bool reading = false;
  Bytes bytes; bool ok = true;
  void U64(std::uint64_t& value) {
    if (!ok || bytes.size() > kMaxSettingsPublicationOperationBytes - 8) { ok = false; return; }
    for (unsigned i = 0; i < 8; ++i) bytes.push_back(static_cast<std::uint8_t>(value >> (i * 8)));
  }
  void U32(unsigned& value) {
    if (!ok || bytes.size() > kMaxSettingsPublicationOperationBytes - 4) { ok = false; return; }
    for (unsigned i = 0; i < 4; ++i) bytes.push_back(static_cast<std::uint8_t>(value >> (i * 8)));
  }
  void Text(std::string& text, std::size_t limit) {
    if (text.size() > limit) { ok = false; return; }
    unsigned size = static_cast<unsigned>(text.size()); U32(size);
    if (!ok || text.size() > kMaxSettingsPublicationOperationBytes - bytes.size()) { ok = false; return; }
    bytes.insert(bytes.end(), text.begin(), text.end());
  }
};
struct Reader {
  static constexpr bool reading = true;
  const Bytes& bytes; std::size_t offset = 0; bool ok = true;
  void U64(std::uint64_t& value) {
    if (!ok || bytes.size() - offset < 8) { ok = false; return; }
    value = 0; for (unsigned i = 0; i < 8; ++i) value |= std::uint64_t(bytes[offset++]) << (i * 8);
  }
  void U32(unsigned& value) {
    if (!ok || bytes.size() - offset < 4) { ok = false; return; }
    value = 0; for (unsigned i = 0; i < 4; ++i) value |= unsigned(bytes[offset++]) << (i * 8);
  }
  void Text(std::string& text, std::size_t limit) {
    unsigned size = 0; U32(size);
    if (!ok || size > limit || size > bytes.size() - offset) { ok = false; return; }
    text.assign(reinterpret_cast<const char*>(bytes.data() + offset), size); offset += size;
  }
};
template<class C, class V> void Count(C& c, V& values, unsigned maximum) {
  unsigned count = static_cast<unsigned>(values.size()); c.U32(count);
  if (!c.ok || count > maximum) { c.ok = false; return; }
  if constexpr (C::reading) values.resize(count);
}
template<class C, class T> void Presence(C& c, std::optional<T>& value) {
  unsigned present = value ? 1 : 0; c.U32(present);
  if (!c.ok || present > 1) { c.ok = false; return; }
  if constexpr (C::reading) { if (present) value.emplace(); else value.reset(); }
}
// Version 3 of an operation (2 of a request) adds where a program without a working folder starts; it is
// written only when that is the install root, so the bytes of every other publication are unchanged.
bool StartsInInstallRoot(const RuntimeInstall& r, const SettingsLaunchPlan& p) {
  return r.launch_in_install_root || p.launch_entry.in_install_root;
}
template<class C> void IdentityPayload(C& c, RuntimeInstall& r, SettingsLaunchPlan& p, bool with_root) {
  c.U32(r.schema_version); c.Text(r.install_id, 64); c.Text(r.title_id, 9); c.U32(r.runtime_number);
  c.Text(r.data_root, 511); c.Text(r.default_profile_id, 64); c.Text(r.runtime_bundle_id, 64);
  c.Text(r.recipe_id, 64); c.Text(r.recipe_version, 64); c.U64(r.settings_revision); c.Text(r.exit_policy, 15);
  c.Text(r.launch_entry_id, 128); c.Text(r.launch_path, 1024); c.Text(r.launch_arguments, 4096);
  c.Text(r.launch_working_directory, 1024); c.Text(r.install_path, 1024); c.Text(r.volume_id, 128);
  unsigned state = static_cast<unsigned>(r.state); c.U32(state);
  if (state > static_cast<unsigned>(PreparationState::kRemoving)) c.ok = false;
  if constexpr (C::reading) r.state = static_cast<PreparationState>(state);
  Count(c, r.artifacts, 32);
  for (auto& a : r.artifacts) { c.Text(a.artifact_id, 128); c.Text(a.identity, 128); c.Text(a.sha256, 64); }
  Presence(c, r.last_failure);
  if (r.last_failure) { c.Text(r.last_failure->code, 128); c.Text(r.last_failure->message, 1024); }
  Presence(c, r.journal);
  if (r.journal) { c.Text(r.journal->operation_id, 128); c.Text(r.journal->operation, 128); c.Text(r.journal->step, 128); }
  c.U32(p.app_id); c.Text(p.recipe_id, 64); c.Text(p.recipe_version, 64); c.Text(p.profile_id, 64);
  c.Text(p.profile_bytes, 8192); c.U64(p.settings_revision); c.Text(p.launch_entry_id, 128);
  Count(c, p.input_presets, 64);
  for (auto& input : p.input_presets) { c.Text(input.first, 64); c.Text(input.second, 8192); }
  c.Text(p.dxvk_config, kDxvkLimit); Count(c, p.registry, 2);
  for (auto& value : p.registry) { c.Text(value.key, 1024); c.Text(value.name, 64); c.Text(value.data, 128); }
  c.Text(p.launch_entry.id, 128); c.Text(p.launch_entry.label, 1024);
  c.Text(p.launch_entry.executable, 1024); c.Text(p.launch_entry.working_directory, 1024);
  if (with_root) {
    unsigned flags = (r.launch_in_install_root ? 1u : 0u) | (p.launch_entry.in_install_root ? 2u : 0u); c.U32(flags);
    if (flags == 0 || flags > 3) c.ok = false;
    if constexpr (C::reading) { r.launch_in_install_root = flags & 1u; p.launch_entry.in_install_root = flags & 2u; }
  }
}
template<class C> void Payload(C& c, SettingsPublicationOperation& o) {
  std::string magic = StartsInInstallRoot(o.install, o.plan) ? "PWOP3" : "PWOP2"; c.Text(magic, 5);
  if (magic != "PWOP2" && magic != "PWOP3") c.ok = false;
  c.U32(o.schema); c.Text(o.transaction_id, 36); c.Text(o.kit_id, 64); c.U64(o.previous_revision);
  IdentityPayload(c, o.install, o.plan, magic == "PWOP3");
  c.Text(o.descriptor_bytes, 8192); c.Text(o.catalog_bytes, 8192); c.Text(o.metadata_bytes, 32768);
  c.Text(o.previous_receipt_bytes, 8192); c.Text(o.previous_metadata_bytes, 32768);
  std::uint64_t registry_time = static_cast<std::uint64_t>(o.registry_unix_time); c.U64(registry_time);
  if (registry_time > static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max())) c.ok = false;
  if constexpr (C::reading) { if (c.ok) o.registry_unix_time = static_cast<std::int64_t>(registry_time); }
  unsigned present = o.dxvk_before.present ? 1 : 0; c.U32(present);
  if (present > 1) c.ok = false;
  if constexpr (C::reading) o.dxvk_before.present = present != 0;
  c.U32(o.dxvk_before.mode); c.U64(o.dxvk_before.size);
  c.Text(o.dxvk_before.sha256, 64); c.Text(o.dxvk_before.bytes, kDxvkLimit);
  Presence(c, o.registry_backup);
  if (o.registry_backup) {
    c.Text(o.registry_backup->filename, 64); c.U32(o.registry_backup->source_mode);
    c.U64(o.registry_backup->size); c.Text(o.registry_backup->sha256, 64);
  }
}
std::optional<Bytes> PayloadBytes(const SettingsPublicationOperation& operation) {
  auto copy = operation; Writer writer; Payload(writer, copy);
  if (!writer.ok) return std::nullopt;
  return std::move(writer.bytes);
}
bool Reject(std::string* reason, const char* message) { if (reason) *reason = message; return false; }
bool EqualAscii(std::string a, std::string b) {
  auto lower = [](unsigned char ch) { return ch >= 'A' && ch <= 'Z' ? char(ch + 32) : char(ch); };
  std::transform(a.begin(), a.end(), a.begin(), lower); std::transform(b.begin(), b.end(), b.begin(), lower);
  return a == b;
}
bool Digest(std::string_view bytes, const char* expected) {
  const auto hash = HashArtifactBytes(bytes); return hash && *hash == expected;
}
bool CanonicalPath(const std::string& value) {
  if (value.empty() || value[0] != '/') return false;
  std::size_t start = 1;
  for (std::size_t i = 1; i <= value.size(); ++i) {
    if (i < value.size() && value[i] != '/') {
      const unsigned char ch = value[i]; if (ch < 0x20 || ch > 0x7e || ch == '\\') return false;
      continue;
    }
    const auto part = value.substr(start, i - start);
    if (part.empty() || part == "." || part == "..") return false;
    start = i + 1;
  }
  return true;
}
bool OwnedDxvk(const std::string& text) {
  if (text.empty()) return true;
  if (text.size() > kDxvkLimit || text.compare(0, std::strlen(kDxvkHeader), kDxvkHeader) != 0) return false;
  const auto suffix = std::strlen(kDxvkHeader);
  // Accept the renderer's exact current line and the earlier short line.
  // A matching prefix followed by arbitrary text does not establish ownership.
  constexpr const char* rendered_suffix = " Changes here are replaced on the next launch.\n";
  return (text.size() > suffix && text[suffix] == '\n') ||
      text.compare(suffix, std::strlen(rendered_suffix), rendered_suffix) == 0;
}
std::string NormalRelative(std::string text) { std::replace(text.begin(), text.end(), '\\', '/'); return text; }
bool BaseValid(const SettingsPublicationOperation& o, std::string* reason) {
  const auto& r = o.install; const auto& p = o.plan;
  if (o.schema != 1 || o.registry_unix_time < 0 || !ValidateRuntimeInstallRecord(r) ||
      static_cast<unsigned>(r.state) > static_cast<unsigned>(PreparationState::kRemoving) ||
      p.app_id != r.runtime_number || p.recipe_id != r.recipe_id || p.recipe_version != r.recipe_version ||
      p.profile_id != r.default_profile_id || p.settings_revision != r.settings_revision ||
      o.previous_revision > p.settings_revision || p.launch_entry_id != r.launch_entry_id ||
      p.launch_entry.id != r.launch_entry_id || NormalRelative(p.launch_entry.executable) != NormalRelative(r.launch_path) ||
      NormalRelative(p.launch_entry.working_directory) != NormalRelative(r.launch_working_directory) ||
      p.launch_entry.in_install_root != r.launch_in_install_root)
    return Reject(reason, "Frozen OWNER record and launch plan disagree.");
  if (!PayloadBytes(o)) return Reject(reason, "Frozen operation exceeds field or total bounds.");
  const bool has_previous = !o.previous_receipt_bytes.empty();
  if (has_previous != !o.previous_metadata_bytes.empty() || (!has_previous && o.previous_revision))
    return Reject(reason, "Previous publication ownership bytes are missing or incomplete.");
  if (has_previous) {
    PwTitlePublication previous{}; PwTitlePublicationMetadata previous_metadata{};
    if (pw_title_publication_parse(reinterpret_cast<const uint8_t*>(o.previous_receipt_bytes.data()),
          o.previous_receipt_bytes.size(), &previous) != PW_OK ||
        previous.phase != PW_TITLE_PUBLICATION_COMMITTED || previous.transaction_id == o.transaction_id ||
        previous.settings_revision != o.previous_revision || previous.install_id != r.install_id || previous.title_id != r.title_id ||
        !Digest(o.previous_metadata_bytes, previous.publication_sha256) ||
        pw_title_publication_metadata_parse(reinterpret_cast<const uint8_t*>(o.previous_metadata_bytes.data()),
          o.previous_metadata_bytes.size(), &previous_metadata) != PW_OK ||
        previous_metadata.install_id != r.install_id || previous_metadata.title_id != r.title_id ||
        previous_metadata.data_root != r.data_root || previous_metadata.settings_revision != o.previous_revision ||
        std::strcmp(previous_metadata.kit_id, previous.kit_id) ||
        std::strcmp(previous_metadata.runtime_bundle_id, previous.runtime_bundle_id) ||
        std::strcmp(previous_metadata.recipe_id, previous.recipe_id) ||
        std::strcmp(previous_metadata.recipe_version, previous.recipe_version))
      return Reject(reason, "Previous committed receipt and metadata do not bind the same owned publication.");
  }
  PwTitleLaunch launch{}; char error[256]{};
  if (pw_title_launch_parse(o.descriptor_bytes.data(), o.descriptor_bytes.size(), r.title_id.c_str(), &launch, error, sizeof(error)) != PW_OK ||
      launch.app_id != r.runtime_number || launch.settings_revision != p.settings_revision || launch.install_id != r.install_id ||
      launch.data_root != r.data_root || launch.default_profile_id != p.profile_id ||
      launch.runtime_bundle_id != r.runtime_bundle_id || launch.recipe_id != p.recipe_id || launch.recipe_version != p.recipe_version ||
      launch.exit_policy != r.exit_policy ||
      launch.game_root != (launch.schema_version == 3 ? platform::WithoutUsbMountNumber(r.install_path) : r.install_path))
    return Reject(reason, "Frozen descriptor does not match the OWNER record.");
  PwGameProfile profile{};
  if (pw_game_profile_parse(reinterpret_cast<const uint8_t*>(p.profile_bytes.data()), p.profile_bytes.size(), &profile) != PW_OK ||
      profile.app.id != p.profile_id || profile.app.runtime != r.runtime_bundle_id || std::strcmp(profile.app.prefix, "game"))
    return Reject(reason, "Frozen profile is unsupported or has mismatched identities.");
  char prefix[1024], executable[1024], working[1024], storage[513]; const char* words[32];
  std::snprintf(prefix, sizeof(prefix), "%s/library/prefixes/game", r.data_root.c_str());
  if (pw_wine_launch_split(profile.app.arguments, storage, sizeof(storage), words, 32) < 0 ||
      pw_wine_launch_host_dir(prefix, profile.app.executable, executable, sizeof(executable)) ||
      pw_wine_launch_host_dir(prefix, profile.app.working_directory, working, sizeof(working)))
    return Reject(reason, "Frozen profile cannot form a Wine launch.");
  // A USB game published naming no mount: its profile and dxvk.conf name the same form as its descriptor.
  const std::string published_root = launch.schema_version == 3 ? platform::WithoutUsbMountNumber(r.install_path) : r.install_path;
  std::string expected_exe = published_root + "/" + NormalRelative(r.launch_path);
  std::string expected_working = published_root;
  if (!r.launch_working_directory.empty()) expected_working += "/" + NormalRelative(r.launch_working_directory);
  else if (r.launch_in_install_root) {}
  else if (expected_exe.find_last_of('/') != std::string::npos) expected_working = expected_exe.substr(0, expected_exe.find_last_of('/'));
  if (!CanonicalPath(executable) || !CanonicalPath(working) || executable != expected_exe || working != expected_working ||
      o.catalog_bytes != p.profile_id + ".profile\n")
    return Reject(reason, "Frozen launch paths or one-entry catalog disagree.");
  PwTitlePublicationMetadata m{};
  if (pw_title_publication_metadata_parse(reinterpret_cast<const uint8_t*>(o.metadata_bytes.data()), o.metadata_bytes.size(), &m) != PW_OK ||
      m.install_id != r.install_id || m.title_id != r.title_id || m.data_root != r.data_root ||
      m.profile_id != p.profile_id || m.runtime_bundle_id != r.runtime_bundle_id ||
      m.recipe_id != p.recipe_id || m.recipe_version != p.recipe_version || m.kit_id != o.kit_id ||
      m.settings_revision != p.settings_revision || !Digest(p.profile_bytes, m.profile_sha256) ||
      !Digest(o.descriptor_bytes, m.descriptor_sha256) || !Digest(o.catalog_bytes, m.catalog_sha256) ||
      m.input_count != p.input_presets.size() || m.dxvk_path != expected_working + "/dxvk.conf" ||
      !OwnedDxvk(p.dxvk_config) || m.dxvk_present != !p.dxvk_config.empty() ||
      (m.dxvk_present && !Digest(p.dxvk_config, m.dxvk_sha256)))
    return Reject(reason, "Frozen completion metadata does not bind the publication bytes.");
  bool selected = !profile.input.preset[0];
  for (std::size_t i = 0; i < p.input_presets.size(); ++i) {
    const auto& input = p.input_presets[i]; PwGameInput parsed; pw_game_input_init(&parsed);
    if (m.inputs[i].name != input.first || !Digest(input.second, m.inputs[i].sha256) ||
        pw_game_input_parse(reinterpret_cast<const uint8_t*>(input.second.data()), input.second.size(), &parsed) != PW_OK)
      return Reject(reason, "Frozen input preset is unsupported or unbound.");
    const auto wanted = std::string(profile.input.preset) + ".input";
    if (profile.input.preset[0] && EqualAscii(wanted, input.first)) {
      if (selected || wanted != input.first) return Reject(reason, "Selected input preset has an ambiguous alias.");
      selected = true;
    }
  }
  if (!selected || m.registry_count != 2 || p.registry.size() > 2)
    return Reject(reason, "Frozen input or owned registry expectations are incomplete.");
  const auto basename = std::string(profile.app.executable).substr(std::string(profile.app.executable).find_last_of('\\') + 1);
  unsigned owned = 0;
  for (const auto& value : m.registry) {
    const unsigned bit = EqualAscii(value.key, "Software\\Wine\\AppDefaults\\" + basename) && EqualAscii(value.name, "Version") ? 1 :
        EqualAscii(value.key, "Control Panel\\Desktop") && EqualAscii(value.name, "LogPixels") ? 2 : 0;
    if (!bit || (owned & bit)) return Reject(reason, "Registry metadata exceeds the executable-owned policy.");
    owned |= bit;
    std::string expected;
    if (value.kind == PW_TITLE_PUBLICATION_REGISTRY_STRING) expected = "\"" + std::string(value.string_value) + "\"";
    else if (value.kind == PW_TITLE_PUBLICATION_REGISTRY_DWORD) { char number[15]; std::snprintf(number, sizeof(number), "dword:%08x", value.dword); expected = number; }
    unsigned matches = 0;
    for (const auto& desired : p.registry) if (EqualAscii(desired.key, value.key) && EqualAscii(desired.name, value.name)) {
      ++matches; if (desired.data != expected) return Reject(reason, "Desired registry value disagrees with metadata.");
    }
    if (matches > 1 || (!matches && !expected.empty())) return Reject(reason, "Desired registry binding is missing or duplicated.");
  }
  for (const auto& desired : p.registry) {
    bool found = false;
    for (const auto& value : m.registry) if (EqualAscii(desired.key, value.key) && EqualAscii(desired.name, value.name)) found = true;
    if (!found) return Reject(reason, "Desired registry edit exceeds the owned policy.");
  }
  // The before-snapshot holds whatever dxvk.conf was there, Playden's or the game's
  // own: its exact bytes (within the codec bound) and mode, bound by their digest.
  const auto& before = o.dxvk_before;
  if ((!before.present && (before.mode || before.size || !before.sha256.empty() || !before.bytes.empty())) ||
      (before.present && (before.mode > 07777 || before.size != before.bytes.size() ||
       before.sha256.size() != 64 || !Digest(before.bytes, before.sha256.c_str()))))
    return Reject(reason, "Prior DXVK snapshot is not canonical.");
  if (o.registry_backup) {
    const auto& b = *o.registry_backup;
    if (b.filename != "registry-backup-" + o.transaction_id + ".v1" ||
        (b.source_mode != 0600 && b.source_mode != 0644) || b.size > kMaxPublicationRegistryBackupBytes ||
        b.sha256.size() != 64 || !std::all_of(b.sha256.begin(), b.sha256.end(), [](char ch) { return (ch >= '0' && ch <= '9') || (ch >= 'a' && ch <= 'f'); }))
      return Reject(reason, "Frozen registry backup binding is invalid.");
  }
  if (!p.registry.empty() && !o.registry_backup) return Reject(reason, "Registry edits require a frozen original backup.");
  return true;
}
std::optional<std::string> Receipt(const SettingsPublicationOperation& o, bool committed) {
  PwTitlePublication receipt{}; receipt.schema_version = 1;
  receipt.phase = committed ? PW_TITLE_PUBLICATION_COMMITTED : PW_TITLE_PUBLICATION_PENDING;
  auto copy = [](auto& target, const std::string& value) {
    if (value.size() >= sizeof(target)) return false;
    std::memcpy(target, value.c_str(), value.size() + 1); return true;
  };
  if (!copy(receipt.transaction_id, o.transaction_id) || !copy(receipt.install_id, o.install.install_id) ||
      !copy(receipt.title_id, o.install.title_id) || !copy(receipt.kit_id, o.kit_id) ||
      !copy(receipt.runtime_bundle_id, o.install.runtime_bundle_id) || !copy(receipt.recipe_id, o.plan.recipe_id) ||
      !copy(receipt.recipe_version, o.plan.recipe_version) || !copy(receipt.plan_sha256, o.plan_sha256)) return std::nullopt;
  receipt.previous_revision = o.previous_revision; receipt.settings_revision = o.plan.settings_revision;
  if (committed) { auto hash = HashArtifactBytes(o.metadata_bytes); if (!hash || !copy(receipt.publication_sha256, *hash)) return std::nullopt; }
  return SerializePublicationReceipt(receipt);
}
bool FrozenValid(const SettingsPublicationOperation& o, std::string* reason) {
  if (!BaseValid(o, reason)) return false;
  auto payload = PayloadBytes(o); if (!payload) return Reject(reason, "Cannot encode frozen operation.");
  auto hash = HashArtifactBytes(std::string_view(reinterpret_cast<const char*>(payload->data()), payload->size()));
  auto pending = Receipt(o, false), committed = Receipt(o, true);
  if (!hash || *hash != o.plan_sha256 || !pending || !committed ||
      *pending != o.pending_receipt_bytes || *committed != o.committed_receipt_bytes)
    return Reject(reason, "Frozen digest or receipts disagree with the operation.");
  return true;
}
