PublicationOperationLoad CheckBackup(const std::filesystem::path& control, SettingsPublicationOperation operation) {
  if (operation.registry_backup) {
    auto backup = LoadPublicationRegistryBackup(control, operation.transaction_id, *operation.registry_backup);
    if (backup.state != PublicationRecoveryState::kValid)
      return LoadFailure(backup.state == PublicationRecoveryState::kAbsent ? PublicationRecoveryState::kCorrupt : backup.state,
                         "Referenced registry backup is not valid: " + backup.message);
  }
  return {PublicationRecoveryState::kValid, std::move(operation), {}};
}
