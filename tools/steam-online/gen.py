#!/usr/bin/env python3
"""Generates the bridge's export stubs from exports.txt (gbe_fork's steam_api64.dll exports).

Every export jumps through g_slots[i], which DllMain fills from steam_api64_gbe.dll. The names in
OVERRIDDEN are implemented in online.c instead, which calls the emulator's through the same slot.
"""
import sys
from pathlib import Path

OVERRIDDEN = {
    "SteamInternal_FindOrCreateUserInterface",
    "SteamInternal_CreateInterface",
    "SteamAPI_SteamUser_v020",
    "SteamAPI_SteamUser_v021",
    "SteamAPI_SteamUser_v022",
    "SteamAPI_SteamUser_v023",
    "SteamAPI_RegisterCallback",
    "SteamAPI_ManualDispatch_GetNextCallback",
}
DATA = {"g_pSteamClientGameServer"}


def main(exports_path: str, out_dir: str) -> None:
    names = [line.strip() for line in Path(exports_path).read_text().splitlines() if line.strip()]
    missing = OVERRIDDEN - set(names)
    if missing:
        sys.exit(f"exports.txt lacks {sorted(missing)}")
    functions = [name for name in names if name not in DATA]
    out = Path(out_dir)
    stubs = [".text"]
    for index, name in enumerate(functions):
        if name in OVERRIDDEN:
            continue
        stubs += [f".globl {name}", f".p2align 4", f"{name}:", f"  jmpq *g_slots+{8 * index}(%rip)"]
    (out / "stubs.S").write_text("\n".join(stubs) + "\n")
    header = ["/* Generated by gen.py from exports.txt. */", f"#define SLOT_COUNT {len(functions)}"]
    header.append("static const char* const kSlotNames[SLOT_COUNT] = {")
    header += [f'  "{name}",' for name in functions]
    header.append("};")
    for index, name in enumerate(functions):
        if name in OVERRIDDEN:
            header.append(f"#define SLOT_{name} {index}")
    (out / "slots.h").write_text("\n".join(header) + "\n")
    (out / "steam_api64.def").write_text(
        "LIBRARY steam_api64.dll\nEXPORTS\n" + "".join(f"  {name}\n" for name in functions) +
        "".join(f"  {name} DATA\n" for name in sorted(DATA)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
