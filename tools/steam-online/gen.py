#!/usr/bin/env python3
"""Generates the bridge's export stubs from exports.txt (gbe_fork's steam_api64.dll exports).

Every export jumps through g_slots[i], which DllMain fills from steam_api64_gbe.dll. The names in
OVERRIDDEN are implemented in online.c instead, which calls the emulator's through the same slot.
"""
import sys
from pathlib import Path

OVERRIDDEN = {
    "SteamInternal_FindOrCreateUserInterface",
    "SteamInternal_CreateInterface",
    "SteamAPI_SteamUser_v020",
    "SteamAPI_SteamUser_v021",
    "SteamAPI_SteamUser_v022",
    "SteamAPI_SteamUser_v023",
    "SteamAPI_SteamUtils_v009",
    "SteamAPI_SteamUtils_v010",
    "SteamAPI_SteamUtils_v011",
    "SteamAPI_SteamMatchmaking_v009",
    "SteamAPI_SteamFriends_v017",
    "SteamAPI_SteamFriends_v018",
    "SteamAPI_SteamNetworking_v006",
    "SteamAPI_ISteamClient_GetISteamUser",
    "SteamAPI_ISteamClient_GetISteamFriends",
    "SteamAPI_ISteamClient_GetISteamUtils",
    "SteamAPI_ISteamClient_GetISteamMatchmaking",
    "SteamAPI_ISteamClient_GetISteamGenericInterface",
    "SteamAPI_ISteamUser_GetAuthSessionTicket",
    "SteamAPI_ISteamUser_GetAuthTicketForWebApi",
    "SteamAPI_ISteamUser_BeginAuthSession",
    "SteamAPI_ISteamUser_EndAuthSession",
    "SteamAPI_ISteamUser_CancelAuthTicket",
    "SteamAPI_ISteamUser_RequestEncryptedAppTicket",
    "SteamAPI_ISteamUser_GetEncryptedAppTicket",
    "SteamAPI_RegisterCallback",
    "SteamAPI_UnregisterCallback",
    "SteamAPI_RegisterCallResult",
    "SteamAPI_UnregisterCallResult",
    "SteamAPI_RunCallbacks",
    "SteamAPI_ManualDispatch_GetNextCallback",
    "SteamAPI_ManualDispatch_FreeLastCallback",
    "SteamAPI_ManualDispatch_GetAPICallResult",
}
DATA = {"g_pSteamClientGameServer"}


def main(exports_path: str, out_dir: str, arch: str) -> None:
    pe64 = arch == "x86_64"
    prefix = "" if pe64 else "_"  # 32-bit C symbols carry a leading underscore
    names = [line.strip() for line in Path(exports_path).read_text().splitlines() if line.strip()]
    missing = OVERRIDDEN - set(names)
    if missing:
        sys.exit(f"exports.txt lacks {sorted(missing)}")
    functions = [name for name in names if name not in DATA]
    out = Path(out_dir)
    stubs = [".text"]
    for index, name in enumerate(functions):
        if name in OVERRIDDEN:
            continue
        symbol = prefix + name
        jump = f"  jmpq *g_slots+{8 * index}(%rip)" if pe64 else f"  jmpl *_g_slots+{4 * index}"
        stubs += [f".globl {symbol}", ".p2align 4", f"{symbol}:", jump]
    (out / "stubs.S").write_text("\n".join(stubs) + "\n")
    header = ["/* Generated by gen.py from exports.txt. */", f"#define SLOT_COUNT {len(functions)}"]
    header.append("static const char* const kSlotNames[SLOT_COUNT] = {")
    header += [f'  "{name}",' for name in functions]
    header.append("};")
    for index, name in enumerate(functions):
        if name in OVERRIDDEN:
            header.append(f"#define SLOT_{name} {index}")
    (out / "slots.h").write_text("\n".join(header) + "\n")
    (out / "steam_api64.def").write_text(
        f"LIBRARY {'steam_api64.dll' if pe64 else 'steam_api.dll'}\nEXPORTS\n" + "".join(f"  {name}\n" for name in functions) +
        "".join(f"  {name} DATA\n" for name in sorted(DATA)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "x86_64")
